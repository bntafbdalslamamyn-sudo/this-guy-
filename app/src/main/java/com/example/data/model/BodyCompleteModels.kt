@IgnoreExtraProperties
data class ExerciseItem(
    @DocumentId val id: String = "",
    val userId: String = "",
    val dayId: String = "sat",
    val dayOrder: Long = 1L,
    val nameAr: String = "",
    val nameEn: String = "",
    val muscleGroupAr: String = "",
    val muscleGroupEn: String = "",
    val muscleKey: String = "chest",
    val setsCount: Long = 4L,
    val repsRange: String = "8 - 12 تكرار",
    val restSeconds: Long = 90L,
    val instructionsAr: String = "",
    val instructionsEn: String = "",
    val notesAr: String = "",
    val lastWeightKg: Double = 0.0,
    val isCustomModified: Boolean = false,
    @ServerTimestamp val createdAt: Timestamp? = null,
    @ServerTimestamp val updatedAt: Timestamp? = null
) {
    fun toCreateMap(ownerUid: String): Map<String, Any> = mapOf(
        "userId" to ownerUid,
        "dayId" to dayId,
        "dayOrder" to dayOrder,
        "nameAr" to nameAr,
        "nameEn" to nameEn,
        "muscleGroupAr" to muscleGroupAr,
        "muscleGroupEn" to muscleGroupEn,
        "muscleKey" to muscleKey,
        "setsCount" to setsCount,
        "repsRange" to repsRange,
        "restSeconds" to restSeconds,
        "instructionsAr" to instructionsAr,
        "instructionsEn" to instructionsEn,
        "notesAr" to notesAr,
        "lastWeightKg" to lastWeightKg,
        "isCustomModified" to isCustomModified,
        "createdAt" to FieldValue.serverTimestamp(),
        "updatedAt" to FieldValue.serverTimestamp()
    )
}

